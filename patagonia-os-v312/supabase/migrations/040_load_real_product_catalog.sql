-- del sistema de origen (productos dados de baja o sin precio vigente), se
-- cargan tal cual, no se inventa un valor. Los cortes principales de vaca
-- (Asado, Vacio, Bife Ancho, Nalga, Cuadril, etc.) tambien vienen en $1/kg
